function requiredString(value, name) {
  if (typeof value !== "string" || !value.trim()) throw new Error(`${name} must be a non-empty string`);
  return value.trim();
}

function metadataFromPackage(pkg) {
  const amalgam = pkg?.amalgam ?? {};
  return {
    version: requiredString(pkg?.version, "package version"),
    channel: requiredString(amalgam.channel, "amalgam channel"),
    minimumBedrock: requiredString(amalgam.minimum_bedrock, "minimum Bedrock version"),
    scriptApi: requiredString(amalgam.script_api, "Script API version"),
    serverUiApi: requiredString(amalgam.server_ui_api, "Server UI API version")
  };
}

function renderRuntimeMetadata(pkg) {
  const metadata = metadataFromPackage(pkg);
  return [
    "// Generated by tools/version.js from package.json. Do not edit by hand.",
    "export const RUNTIME_METADATA = Object.freeze({",
    `  version: ${JSON.stringify(metadata.version)},`,
    `  channel: ${JSON.stringify(metadata.channel)},`,
    `  minimumBedrock: ${JSON.stringify(metadata.minimumBedrock)},`,
    `  scriptApi: ${JSON.stringify(metadata.scriptApi)},`,
    `  serverUiApi: ${JSON.stringify(metadata.serverUiApi)}`,
    "});",
    ""
  ].join("\n");
}

function numericVersionParts(version, name) {
  const match = requiredString(version, name).match(/^(\d+)\.(\d+)\.(\d+)(?:-[0-9A-Za-z.-]+)?$/);
  if (!match) throw new Error(`${name} must use major.minor.patch versioning`);
  return match.slice(1, 4).map(Number);
}

module.exports = { metadataFromPackage, numericVersionParts, renderRuntimeMetadata };
